#include "libft.h"

void	*ft_memset(void *s, int c, size_t n)
{
	unsigned char	*ptr;
	unsigned char	value;

	ptr = (unsigned char *) s;
	value = (unsigned char) c;
	while (n--)
	{
		*ptr++ = value;
	}
	return (s);
}
